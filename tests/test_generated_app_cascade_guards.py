class Unreadable(Exception):
    """An input could not be read or parsed: an error, never an empty set."""


def read_text(path: Path) -> str:
    """Read a text file; an unreadable or undecodable file is Unreadable."""
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        raise Unreadable(f"{path}: {exc}") from exc


# libyaml speeds the parse of a 170-document render up about 20 times; the pure Python
# loader is the fallback and behaves the same.
_BaseLoader = getattr(yaml, "CSafeLoader", yaml.SafeLoader)


class _StrictLoader(_BaseLoader):
    """SafeLoader that rejects a duplicate mapping key instead of keeping the last."""


def _no_duplicates(loader: yaml.SafeLoader, node: yaml.MappingNode, deep: bool = False):
    seen = set()
    for key_node, _ in node.value:
        key = loader.construct_object(key_node, deep=True)
        try:
            dup = key in seen
            seen.add(key)
        except TypeError:
            raise yaml.constructor.ConstructorError(None, None, "unhashable mapping key", key_node.start_mark)
        if dup:
            raise yaml.constructor.ConstructorError(
                None, None, f"duplicate mapping key {key!r}", key_node.start_mark)
    return yaml.constructor.SafeConstructor.construct_mapping(loader, node, deep)


_StrictLoader.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, _no_duplicates)


