def retire_source(root: Path) -> str:
    path = root / RETIRE
    try:
        doc = yaml.safe_load(read_text(path))
        tmpls = {t["name"]: t for t in doc["spec"]["templates"]}
        return tmpls["argocd-app-guard"]["script"]["source"]
    except (yaml.YAMLError, KeyError, TypeError) as exc:
        raise Unreadable(f"{path}: argocd-app-guard script not found ({exc!r})") from exc


def code_only(source: str) -> str:
    """The script without whole-line comments (a comment is not behaviour)."""
    return "\n".join(l for l in source.splitlines() if not l.lstrip().startswith("#"))


def retire_static(source: str) -> list[str]:
    problems = []
    text = code_only(source)
    delete = text.find('kubectl delete --raw "$APP_URI"')
    wait = text.find("wait_gone 36")
    patches = [m.start() for m in re.finditer(r"\bkubectl\s+patch\b", text)]
    if delete < 0:
        problems.append("the Application delete (kubectl delete --raw \"$APP_URI\") is gone")
    if wait < 0:
        problems.append("the bounded wait for the cascade (wait_gone 36) is gone")
    if len(patches) != 1:
        problems.append(f"expected exactly one kubectl patch, found {len(patches)}")
    elif delete < 0 or wait < 0:
        problems.append("cannot order the delete, the wait and the patch")
    elif not delete < wait < patches[0]:
        problems.append("the finalizer-clearing patch is not after the delete and the wait")
    verbs = re.findall(r"\bkubectl\s+(?:-\S+\s+)*([a-z][a-z-]*)", text)
    for v in sorted(set(verbs) - {"get", "delete", "patch"}):
        problems.append(f"kubectl {v} is used: only get, delete and patch are expected")
    if verbs.count("delete") != 1:
        problems.append(f"expected exactly one kubectl delete, found {verbs.count('delete')}")
    for needle in ("propagationPolicy", "orphanDependents", "--cascade", "--wait=false", '"Orphan"', "=orphan"):
        for m in re.finditer(re.escape(needle), text):
            line = text[: m.start()].count("\n") + 1
            problems.append(f"'{needle}' appears (line {line}): the delete must not ask for orphaning")
            break
    if '"preconditions":{"uid"' not in text:
        problems.append("the delete no longer carries the verified UID as a precondition")
    m = re.search(r"PATCH=\$\(printf '(\[.*?\])'\s*\\?\s*\"\$APP_UID\" \"\$TEAM\"\)", text, flags=re.S)
    if not m:
        problems.append("the finalizer patch (printf with \"$APP_UID\" \"$TEAM\") was not found")
    else:
        args = iter([UID, TEAM])
        try:
            ops = json.loads(re.sub(r"%s", lambda _: next(args), m.group(1)))
        except (ValueError, StopIteration) as exc:
            ops = None
            problems.append(f"the finalizer patch is not the expected JSON ({exc})")
        if ops is not None and ops != EXPECTED_PATCH:
            problems.append(f"the finalizer patch operations differ from the pinned list: {ops}")
    return problems


