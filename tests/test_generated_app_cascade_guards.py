_EXPR = re.compile(rf"{LB}\s*(.*?)\s*{RB}")


def git_directory_patterns(name: str, doc: dict) -> list[str]:
    gens = (doc.get("spec") or {}).get("generators")
    if not isinstance(gens, list) or not gens:
        raise Unreadable(f"ApplicationSet {name}: no generators list")
    out = []
    for g in gens:
        git = g.get("git") if isinstance(g, dict) and set(g) == {"git"} else None
        dirs = git.get("directories") if isinstance(git, dict) else None
        if not isinstance(dirs, list) or not dirs or git.get("files"):
            raise Unreadable(f"ApplicationSet {name}: only git directory generators are modelled")
        for d in dirs:
            if not isinstance(d, dict) or set(d) != {"path"} or not isinstance(d["path"], str) \
                    or "__TPL__" in d["path"]:
                raise Unreadable(f"ApplicationSet {name}: directory entry not modelled ({d!r})")
            out.append(d["path"])
    return out


def render_name(name: str, template: object, rel: Path) -> str:
    if not isinstance(template, str):
        raise Unreadable(f"ApplicationSet {name}: no name template")
    segments = list(rel.parts)

    def sub(m: re.Match) -> str:
        expr = m.group(1)
        idx = re.fullmatch(r"index \.path\.segments (\d+)", expr)
        if idx:
            n = int(idx.group(1))
            if n >= len(segments):
                raise Unreadable(f"ApplicationSet {name}: segment {n} is outside {rel}")
            return segments[n]
        if expr == ".path.basename":
            return segments[-1]
        if expr == ".path.path":
            return rel.as_posix()
        raise Unreadable(f"ApplicationSet {name}: template action {expr!r} is not modelled")

    rendered = _EXPR.sub(sub, template)
    if LB in rendered or RB in rendered or "__TPL__" in rendered or not rendered:
        raise Unreadable(f"ApplicationSet {name}: name template not renderable ({template!r})")
    return rendered


def generated_names(root: Path, appsets: dict[str, dict]) -> dict[str, list[str]]:
    """Name -> list of sources that produce it, over the real tree."""
    names: dict[str, list[str]] = {}
    for set_name in sorted(EXPECTED_CASCADE):
        doc = appsets.get(set_name)
        if doc is None:
            raise Unreadable(f"ApplicationSet {set_name} not found: generated names cannot be derived")
        shape = shape_findings(set_name, doc)
        if shape:
            raise Unreadable("; ".join(shape))
        template = (((doc.get("spec") or {}).get("template") or {}).get("metadata") or {}).get("name")
        for pattern in git_directory_patterns(set_name, doc):
            matches = sorted(p.relative_to(root) for p in root.glob(pattern) if p.is_dir())
            if not matches:
                raise Unreadable(f"ApplicationSet {set_name}: generator path {pattern} matches nothing")
            for rel in matches:
                names.setdefault(render_name(set_name, template, rel), []).append(
                    f"{set_name}:{rel.as_posix()}")
    return names


def handwritten_names(root: Path) -> list[str]:
    return [str(doc["metadata"]["name"]) for _, doc in docs_of_kind(root, "Application")
            if isinstance(doc.get("metadata"), dict) and doc["metadata"].get("name")]


def name_findings(generated: dict[str, list[str]], handwritten: list[str]) -> list[str]:
    problems = []
    for name, sources in sorted(generated.items()):
        if len(sources) > 1:
            problems.append(f"generated name {name} is produced by {sources}")
    for hw in handwritten:
        # a templated hand-written name (marker) is matched as a pattern, so an
        # unresolvable name can only over-report, never hide a collision
        pattern = "^" + ".*".join(re.escape(p) for p in hw.split("__TPL__")) + "$"
        for name in generated:
            if re.match(pattern, name):
                problems.append(f"generated name {name} equals hand-written Application {hw}")
    return problems


