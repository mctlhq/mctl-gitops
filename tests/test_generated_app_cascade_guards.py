def _glob(pattern: str, value: str) -> bool:
    """Glob match. Brace alternation and backslash escapes are not modelled."""
    if any(c in pattern for c in "{}\\"):
        raise Unreadable(f"glob syntax not modelled: {pattern!r}")
    return fnmatch.fnmatchcase(value, pattern)


def _in_list(group: str, kind: str, entries: list, named: str | None = None) -> bool:
    for e in entries:
        if _glob(e.get("group", ""), group) and _glob(e.get("kind", ""), kind):
            if named is None or not e.get("name") or _glob(e["name"], named):
                return True
    return False


def _dest_ok(project: dict, server: str, namespace: str) -> bool:
    for d in (project.get("spec") or {}).get("destinations") or []:
        for key in ("server", "namespace"):
            if str(d.get(key, "")).startswith("!"):
                raise Unreadable("negated destination entries are not modelled")
        if d.get("name"):
            raise Unreadable("destination by name is not modelled; use the server URL form")
        if _glob(d.get("server", ""), server) and _glob(d.get("namespace", ""), namespace):
            return True
    return False


def resource_permitted(project: dict, server: str, res: dict) -> bool:
    spec = project.get("spec") or {}
    if spec.get("permitOnlyProjectScopedClusters") not in (None, False):
        raise Unreadable("permitOnlyProjectScopedClusters is set: project-scoped clusters are not modelled")
    group, kind, ns, name = res.get("group", ""), res["kind"], res.get("namespace", ""), res.get("name", "")
    if ns:
        wl = spec.get("namespaceResourceWhitelist")      # None = every kind (Argo semantics)
        bl = spec.get("namespaceResourceBlacklist") or []
        listed = wl is None or (len(wl) != 0 and _in_list(group, kind, wl))
        if not listed or (bl and _in_list(group, kind, bl)):
            return False
        return _dest_ok(project, server, ns)
    wl = spec.get("clusterResourceWhitelist") or []
    bl = spec.get("clusterResourceBlacklist") or []
    return len(wl) != 0 and _in_list(group, kind, wl, name) and not (bl and _in_list(group, kind, bl, name))


def cascade_uncovered(app: dict, project: dict) -> list[dict]:
    """Managed resources of `app` that a cascade delete would leave behind."""
    server = ((app.get("spec") or {}).get("destination") or {}).get("server", "")
    resources = (app.get("status") or {}).get("resources")
    if not isinstance(resources, list):
        raise Unreadable(f"{(app.get('metadata') or {}).get('name')}: no status.resources list")
    return [r for r in resources if not resource_permitted(project, server, r)]


def cli_cascade_coverage(apps_path: str, project_path: str, project_name: str) -> int:
    try:
        apps = json.loads(read_text(Path(apps_path)))["items"]
        proj_docs = [d for d in yaml.safe_load_all(read_text(Path(project_path))) if isinstance(d, dict)]
        if "items" in (proj_docs[0] if proj_docs else {}):
            proj_docs = proj_docs[0]["items"]
        projects = [d for d in proj_docs if d.get("kind") == "AppProject"]
        if len(projects) != 1:
            raise Unreadable(f"expected exactly one AppProject in {project_path}, found {len(projects)}")
        selected = [a for a in apps if (a.get("spec") or {}).get("project") == project_name]
        if not selected:
            raise Unreadable(f"no Application in project {project_name}")
        bad = 0
        for app in selected:
            for r in cascade_uncovered(app, projects[0]):
                bad += 1
                print(f"UNCOVERED {app['metadata']['name']}: {r.get('group', '')}/{r['kind']} "
                      f"{r.get('namespace', '')}/{r.get('name', '')}")
        print(f"{len(selected)} Applications checked, {bad} resource(s) a cascade would skip")
        return 1 if bad else 0
    except (OSError, ValueError, KeyError, IndexError, TypeError, AttributeError,
            yaml.YAMLError, Unreadable) as exc:
        print(f"UNREADABLE: {exc}", file=sys.stderr)
        return 2


