def controller_finalizers(preserve: bool, template_finalizers: list | None) -> list:
    """Model of RenderTemplateParams at Argo CD v3.3.8."""
    template_finalizers = list(template_finalizers or [])
    if not preserve and not template_finalizers:
        return [RESOURCES_FINALIZER]
    return template_finalizers


def generator_override_paths(node, path: str) -> list[str]:
    """Paths of `template` / `templatePatch` keys anywhere below the generators.

    A generator (git, matrix, merge, ...) may carry its own template, which
    overrides spec.template for the Applications it produces.
    """
    out = []
    if isinstance(node, dict):
        for key, value in node.items():
            if key in ("template", "templatePatch"):
                out.append(f"{path}.{key}")
            out += generator_override_paths(value, f"{path}.{key}")
    elif isinstance(node, list):
        for i, value in enumerate(node):
            out += generator_override_paths(value, f"{path}[{i}]")
    return out


def shape_findings(name: str, doc: dict) -> list[str]:
    """Keys that change what is rendered and that this script does not model."""
    problems = []
    spec = doc.get("spec")
    if not isinstance(spec, dict):
        return [f"ApplicationSet {name}: spec is not a mapping"]
    for key in sorted(map(str, set(spec) - SPEC_KEYS)):
        why = "changes how Applications are rendered and is not modelled" \
            if key in UNMODELLED_RENDERING_KEYS else "is an unknown spec key"
        problems.append(f"ApplicationSet {name}: spec.{key} {why}; model and pin it before using it")
    for where in generator_override_paths(spec.get("generators"), "spec.generators"):
        problems.append(f"ApplicationSet {name}: {where} overrides what is rendered and is not modelled")
    tmpl = spec.get("template")
    if not isinstance(tmpl, dict):
        problems.append(f"ApplicationSet {name}: spec.template is not a mapping")
        return problems
    for key in sorted(map(str, set(tmpl) - TEMPLATE_KEYS)):
        problems.append(f"ApplicationSet {name}: spec.template.{key} is an unknown key")
    meta = tmpl.get("metadata")
    if not isinstance(meta, dict):
        problems.append(f"ApplicationSet {name}: spec.template.metadata is not a mapping")
    else:
        for key in sorted(map(str, set(meta) - TEMPLATE_META_KEYS)):
            problems.append(f"ApplicationSet {name}: spec.template.metadata.{key} is an unknown key")
    policy = spec.get("syncPolicy")
    if policy is not None and not isinstance(policy, dict):
        problems.append(f"ApplicationSet {name}: spec.syncPolicy is not a mapping")
    elif isinstance(policy, dict):
        for key in sorted(map(str, set(policy) - SYNC_POLICY_KEYS)):
            problems.append(f"ApplicationSet {name}: spec.syncPolicy.{key} is an unknown key")
    return problems


def appset_findings(appsets: dict[str, dict]) -> list[str]:
    problems = []
    for name, doc in sorted(appsets.items()):
        shape = shape_findings(name, doc)
        problems += shape
        if shape:
            continue
        spec = doc.get("spec") or {}
        policy = spec.get("syncPolicy") or {}
        preserve = policy.get("preserveResourcesOnDeletion", False)
        if not isinstance(preserve, bool):
            problems.append(f"ApplicationSet {name}: preserveResourcesOnDeletion is not a boolean")
            continue
        tmpl_fin = ((spec.get("template") or {}).get("metadata") or {}).get("finalizers")
        cascade = RESOURCES_FINALIZER in controller_finalizers(preserve, tmpl_fin)
        if name not in EXPECTED_CASCADE:
            problems.append(
                f"ApplicationSet {name} is not in EXPECTED_CASCADE (cascade would be {cascade}); "
                "record its finalizer outcome deliberately")
        elif cascade != EXPECTED_CASCADE[name]:
            problems.append(
                f"ApplicationSet {name}: generated Applications would "
                f"{'cascade' if cascade else 'NOT cascade'} on delete, expected "
                f"{'cascade' if EXPECTED_CASCADE[name] else 'no cascade'} "
                f"(preserveResourcesOnDeletion={preserve}, template finalizers={tmpl_fin})")
        if (policy.get("applicationsSync") or "sync") != "sync":
            problems.append(f"ApplicationSet {name}: applicationsSync is not the default (sync)")
    for name in EXPECTED_CASCADE:
        if name not in appsets:
            problems.append(f"ApplicationSet {name} listed in EXPECTED_CASCADE was not found")
    return problems



def matrix_findings(renders: list[Render]) -> list[str]:
    """G1 on every render, and every render must yield the same sets as the default one."""
    problems: list[str] = []
    default = renders[0]
    default_sets = appsets_of(default)
    seen: set[str] = set()
    for r in renders:
        sets = appsets_of(r)
        seen |= set(sets)
        for p in appset_findings(sets):
            problems.append(p if r is default else f"{p} (render: {r.label})")
        if r is default:
            continue
        for name, doc in sorted(sets.items()):
            if name in default_sets and pinned_view(doc) != pinned_view(default_sets[name]):
                problems.append(f"ApplicationSet {name} renders differently under {r.label}: a values flag "
                                "changes a pinned field")
    for name in sorted(seen - set(default_sets)):
        problems.append(f"ApplicationSet {name} is rendered only under {', '.join(r.label for r in renders if name in appsets_of(r))[:200]}: "
                        "a values flag hides it from the default render")
    return sorted(set(problems))


