EXPECTED_CASCADE = {"apps": True, "tenants": True}

# Sentinels for a Go-template action that Helm passes through as a literal
# (`{{ `...` }}`): kept readable so name templates and paths can be pinned.
LB, RB = "⟦", "⟧"


class Unreadable(Exception):
    """An input could not be read or parsed: an error, never an empty set."""


def read_text(path: Path) -> str:
    """Read a text file; an unreadable or undecodable file is Unreadable."""
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        raise Unreadable(f"{path}: {exc}") from exc


# --------------------------------------------------------------------------
# Template-tolerant YAML loading
# --------------------------------------------------------------------------

def neutral(text: str, keep_literals: bool = False) -> str:
    """Replace Helm actions with a marker so the file parses as YAML.

    With keep_literals, a Helm raw string that wraps a Go-template action
    keeps its content (with sentinel brackets) instead of becoming a marker.
    """
    text = re.sub(r"\{\{-?\s*/\*.*?\*/\s*-?\}\}[ \t]*\n?", "", text, flags=re.S)
    text = re.sub(r"^[ \t]*\{\{-?\s*(?:if|else|end|range|with|define)\b.*?\}\}[ \t]*\n",
                  "", text, flags=re.M)
    if keep_literals:
        def keep(m: re.Match) -> str:
            return m.group(1).replace("{{", LB).replace("}}", RB)
        text = re.sub(r"\{\{\s*`(.*?)`\s*\}\}", keep, text, flags=re.S)
    text = re.sub(r"\{\{\s*`.*?`\s*\}\}", "__TPL__", text, flags=re.S)
    text = re.sub(r"\{\{-?.*?-?\}\}", "__TPL__", text, flags=re.S)
    return text


def unlit(value):
    """Turn sentinel brackets back into Go-template braces, recursively."""
    if isinstance(value, str):
        return value.replace(LB, "{{").replace(RB, "}}")
    if isinstance(value, list):
        return [unlit(v) for v in value]
    if isinstance(value, dict):
        return {unlit(k): unlit(v) for k, v in value.items()}
    return value


def parse_docs(text: str, path: Path, keep_literals: bool = False) -> list[dict]:
    try:
        docs = list(yaml.safe_load_all(neutral(text, keep_literals)))
    except yaml.YAMLError as exc:
        raise Unreadable(f"{path}: {exc}") from exc
    return [d for d in docs if isinstance(d, dict)]


def docs_of_kind(root: Path, kind: str, keep_literals: bool = False) -> list[tuple[Path, dict]]:
    out = []
    base = root / BOOTSTRAP
    if not base.is_dir():
        raise Unreadable(f"{base} is not a directory")
    for path in sorted(base.rglob("*.yaml")):
        text = read_text(path)
        if not re.search(rf"^kind:\s*{kind}\s*$", text, flags=re.M):
            continue
        for doc in parse_docs(text, path, keep_literals):
            if doc.get("kind") == kind:
                out.append((path, doc))
    return out


# --------------------------------------------------------------------------
# G1: finalizer outcome per ApplicationSet
# --------------------------------------------------------------------------

def controller_finalizers(preserve: bool, template_finalizers: list | None) -> list:
    """Model of RenderTemplateParams at Argo CD v3.3.8."""
    template_finalizers = list(template_finalizers or [])
    if not preserve and not template_finalizers:
        return [RESOURCES_FINALIZER]
    return template_finalizers


def appset_findings(appsets: dict[str, dict]) -> list[str]:
    problems = []
    for name, doc in sorted(appsets.items()):
        spec = doc.get("spec") or {}
        policy = spec.get("syncPolicy") or {}
        preserve = policy.get("preserveResourcesOnDeletion", False)
        if not isinstance(preserve, bool):
            problems.append(f"ApplicationSet {name}: preserveResourcesOnDeletion is not a boolean")
            continue
        tmpl_fin = ((spec.get("template") or {}).get("metadata") or {}).get("finalizers")
        cascade = RESOURCES_FINALIZER in controller_finalizers(preserve, tmpl_fin)
        if name not in EXPECTED_CASCADE:
            problems.append(
                f"ApplicationSet {name} is not in EXPECTED_CASCADE (cascade would be {cascade}); "
                "record its finalizer outcome deliberately")
        elif cascade != EXPECTED_CASCADE[name]:
            problems.append(
                f"ApplicationSet {name}: generated Applications would "
                f"{'cascade' if cascade else 'NOT cascade'} on delete, expected "
                f"{'cascade' if EXPECTED_CASCADE[name] else 'no cascade'} "
                f"(preserveResourcesOnDeletion={preserve}, template finalizers={tmpl_fin})")
        if (policy.get("applicationsSync") or "sync") != "sync":
            problems.append(f"ApplicationSet {name}: applicationsSync is not the default (sync)")
    for name in EXPECTED_CASCADE:
        if name not in appsets:
            problems.append(f"ApplicationSet {name} listed in EXPECTED_CASCADE was not found")
    return problems


def load_appsets(root: Path) -> dict[str, dict]:
    sets: dict[str, dict] = {}
    for path, doc in docs_of_kind(root, "ApplicationSet", keep_literals=True):
        name = (doc.get("metadata") or {}).get("name")
        if not isinstance(name, str) or "__TPL__" in name:
            raise Unreadable(f"{path}: ApplicationSet name not resolvable ({name!r})")
        if name in sets:
            raise Unreadable(f"{path}: duplicate ApplicationSet {name}")
        sets[name] = doc
    return sets


