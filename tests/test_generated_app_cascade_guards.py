"""Cascade and ownership guards for generated applications.

Applications generated by an ApplicationSet are not plain objects: what happens
to the workloads behind them when the Application is deleted depends on three
things that live in different places, and each one can be changed by an
unrelated-looking edit.

G1. Finalizer. The ApplicationSet controller (Argo CD v3.3.8,
    applicationset/utils/utils.go, RenderTemplateParams) adds
    `resources-finalizer.argocd.argoproj.io` to every generated Application
    when the template carries no finalizer of its own and
    `syncPolicy.preserveResourcesOnDeletion` is not true. On update it also
    overwrites the Application's finalizers with the generated set
    (applicationset_controller.go, createOrUpdateInCluster), so flipping the
    flag to true strips the finalizer from every live Application, and
    deleting such an Application then leaves its Deployments, Services and
    ExternalSecrets running. Every ApplicationSet in the bootstrap chart is
    listed here with the finalizer outcome it is expected to have; a new
    ApplicationSet, or a changed outcome, fails until this table is edited on
    purpose.
G2. Names. The controller finds an existing Application by name and updates it
    (createOrUpdateInCluster); an Application that has no controller owner is
    adopted and its spec and finalizers are replaced. Two generated names that
    coincide, or a generated name that coincides with a hand-written
    Application, are therefore not an error but a takeover. The names that
    `apps` (`<team>-<service>`) and `tenants` (`tenant-<tenant>`) generate over
    the real tree must be pairwise distinct and must not equal a hand-written
    Application name.
G3. Retire order. retire-service deletes the Application with the verified UID
    as a precondition, waits for Argo CD to cascade, and only after the wait
    clears finalizers, with a patch that tests the UID and the project first.
    The finalizer must never be cleared before the wait, the delete must not
    ask for orphaning, and the patch must stay pinned.
G4. Cascade coverage. Argo CD deletes on cascade only live objects that the
    Application's project permits (appcontroller.go, getPermittedAppLiveObjects
    -> AppProject.IsLiveResourcePermitted): a kind outside the whitelist or in
    the blacklist, a namespace outside the destinations, or a cluster-scoped
    object with an empty cluster whitelist is skipped. `cascade_uncovered()`
    models that rule; it is self-tested here and is available as an offline
    read-only check over a saved export:

        python3 tests/test_generated_app_cascade_guards.py \\
            --cascade-coverage APPLICATIONS.json PROJECT.yaml --project NAME

    prints every managed resource of the Applications in that project that the
    given AppProject would not cascade, exit 1 if any, exit 2 if an input
    cannot be read (unreadable is never "all covered").

Every detector is proven both ways by the self-test: green on the converged
input and red on a deliberate mutation of it. No pytest, matching the plain
`python3 tests/<file>.py` convention.

Run: python3 tests/test_generated_app_cascade_guards.py [--root DIR]
"""
from __future__ import annotations

import copy
import fnmatch
import json
import re
import sys
import tempfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
RESOURCES_FINALIZER = "resources-finalizer.argocd.argoproj.io"
BOOTSTRAP = Path("platform-gitops/bootstrap/templates")
RETIRE = Path("platform-gitops/argo-workflows/cluster-templates/wft-retire-service.yaml")

# ApplicationSet name -> does a delete of one of its Applications cascade to
# the workloads? Both existing sets are `preserveResourcesOnDeletion: false`.
EXPECTED_CASCADE = {"apps": True, "tenants": True}


class Unreadable(Exception):
    """An input could not be read or parsed: an error, never an empty set."""


# --------------------------------------------------------------------------
# Template-tolerant YAML loading
# --------------------------------------------------------------------------

def neutral(text: str) -> str:
    """Replace Helm actions with a marker so the file parses as YAML."""
    text = re.sub(r"\{\{-?\s*/\*.*?\*/\s*-?\}\}[ \t]*\n?", "", text, flags=re.S)
    text = re.sub(r"^[ \t]*\{\{-?\s*(?:if|else|end|range|with|define)\b.*?\}\}[ \t]*\n",
                  "", text, flags=re.M)
    text = re.sub(r"\{\{\s*`.*?`\s*\}\}", "__TPL__", text, flags=re.S)
    text = re.sub(r"\{\{-?.*?-?\}\}", "__TPL__", text, flags=re.S)
    return text


def load_docs(path: Path) -> list[dict]:
    try:
        docs = list(yaml.safe_load_all(neutral(path.read_text())))
    except (OSError, yaml.YAMLError) as exc:
        raise Unreadable(f"{path}: {exc}") from exc
    return [d for d in docs if isinstance(d, dict)]


def docs_of_kind(root: Path, kind: str) -> list[tuple[Path, dict]]:
    out = []
    base = root / BOOTSTRAP
    if not base.is_dir():
        raise Unreadable(f"{base} is not a directory")
    for path in sorted(base.rglob("*.yaml")):
        text = path.read_text()
        if not re.search(rf"^kind:\s*{kind}\s*$", text, flags=re.M):
            continue
        for doc in load_docs(path):
            if doc.get("kind") == kind:
                out.append((path, doc))
    return out


# --------------------------------------------------------------------------
# G1: finalizer outcome per ApplicationSet
# --------------------------------------------------------------------------

def controller_finalizers(preserve: bool, template_finalizers: list | None) -> list:
    """Model of RenderTemplateParams at Argo CD v3.3.8."""
    template_finalizers = list(template_finalizers or [])
    if not preserve and not template_finalizers:
        return [RESOURCES_FINALIZER]
    return template_finalizers


def appset_findings(appsets: dict[str, dict]) -> list[str]:
    problems = []
    for name, doc in sorted(appsets.items()):
        spec = doc.get("spec") or {}
        policy = spec.get("syncPolicy") or {}
        preserve = policy.get("preserveResourcesOnDeletion", False)
        if not isinstance(preserve, bool):
            problems.append(f"ApplicationSet {name}: preserveResourcesOnDeletion is not a boolean")
            continue
        tmpl_fin = ((spec.get("template") or {}).get("metadata") or {}).get("finalizers")
        cascade = RESOURCES_FINALIZER in controller_finalizers(preserve, tmpl_fin)
        if name not in EXPECTED_CASCADE:
            problems.append(
                f"ApplicationSet {name} is not in EXPECTED_CASCADE (cascade would be {cascade}); "
                "record its finalizer outcome deliberately")
        elif cascade != EXPECTED_CASCADE[name]:
            problems.append(
                f"ApplicationSet {name}: generated Applications would "
                f"{'cascade' if cascade else 'NOT cascade'} on delete, expected "
                f"{'cascade' if EXPECTED_CASCADE[name] else 'no cascade'} "
                f"(preserveResourcesOnDeletion={preserve}, template finalizers={tmpl_fin})")
        if (policy.get("applicationsSync") or "sync") != "sync":
            problems.append(f"ApplicationSet {name}: applicationsSync is not the default (sync)")
    for name in EXPECTED_CASCADE:
        if name not in appsets:
            problems.append(f"ApplicationSet {name} listed in EXPECTED_CASCADE was not found")
    return problems


def load_appsets(root: Path) -> dict[str, dict]:
    sets: dict[str, dict] = {}
    for path, doc in docs_of_kind(root, "ApplicationSet"):
        name = (doc.get("metadata") or {}).get("name")
        if not isinstance(name, str) or "__TPL__" in name:
            raise Unreadable(f"{path}: ApplicationSet name not resolvable ({name!r})")
        if name in sets:
            raise Unreadable(f"{path}: duplicate ApplicationSet {name}")
        sets[name] = doc
    return sets


# --------------------------------------------------------------------------
# G2: generated names are distinct
# --------------------------------------------------------------------------

def generated_names(root: Path) -> dict[str, list[str]]:
    """Name -> list of sources that produce it, over the real tree."""
    names: dict[str, list[str]] = {}
    svc = root / "platform-gitops/services"
    ten = root / "platform-gitops/tenants"
    if not svc.is_dir() or not ten.is_dir():
        raise Unreadable("services/ or tenants/ is not a directory")
    for team in sorted(p for p in svc.iterdir() if p.is_dir()):
        for s in sorted(p for p in team.iterdir() if p.is_dir()):
            names.setdefault(f"{team.name}-{s.name}", []).append(f"apps:{team.name}/{s.name}")
    for t in sorted(p for p in ten.iterdir() if p.is_dir()):
        names.setdefault(f"tenant-{t.name}", []).append(f"tenants:{t.name}")
    return names


def handwritten_names(root: Path) -> list[str]:
    return [str(doc["metadata"]["name"]) for _, doc in docs_of_kind(root, "Application")
            if isinstance(doc.get("metadata"), dict) and doc["metadata"].get("name")]


def name_findings(generated: dict[str, list[str]], handwritten: list[str]) -> list[str]:
    problems = []
    for name, sources in sorted(generated.items()):
        if len(sources) > 1:
            problems.append(f"generated name {name} is produced by {sources}")
    for hw in handwritten:
        # a templated hand-written name (marker) is matched as a pattern, so an
        # unresolvable name can only over-report, never hide a collision
        pattern = "^" + ".*".join(re.escape(p) for p in hw.split("__TPL__")) + "$"
        for name in generated:
            if re.match(pattern, name):
                problems.append(f"generated name {name} equals hand-written Application {hw}")
    return problems


# --------------------------------------------------------------------------
# G3: retire order
# --------------------------------------------------------------------------

def retire_findings(text: str) -> list[str]:
    problems = []
    delete = text.find('kubectl delete --raw "$APP_URI"')
    wait = text.find("wait_gone 36")
    strip = [m.start() for m in re.finditer(r'"op":"add","path":"/metadata/finalizers"', text)]
    if delete < 0:
        problems.append("the Application delete (kubectl delete --raw \"$APP_URI\") is gone")
    if wait < 0:
        problems.append("the bounded wait for the cascade (wait_gone 36) is gone")
    if len(strip) != 1:
        problems.append(f"expected exactly one finalizer-clearing patch, found {len(strip)}")
    elif -1 < delete < wait and not (delete < wait < strip[0]):
        problems.append("the finalizer-clearing patch is not after the delete and the wait")
    elif delete < 0 or wait < 0:
        problems.append("cannot order the delete, the wait and the patch")
    if re.search(r"\bkubectl\s+patch\b[^\n]*finalizers", text.replace('"op":"add","path":"/metadata/finalizers"', "")):
        problems.append("a second finalizer-touching kubectl patch exists")
    for needle in ("propagationPolicy", "orphanDependents", "--cascade", "--wait=false", '"Orphan"', "=orphan"):
        for m in re.finditer(re.escape(needle), text):
            line = text[: m.start()].count("\n") + 1
            problems.append(f"'{needle}' appears (line {line}): the delete must not ask for orphaning")
            break
    if '"preconditions":{"uid"' not in text:
        problems.append("the delete no longer carries the verified UID as a precondition")
    patch = re.search(r"PATCH=\$\(printf '(\[.*?\])'", text, flags=re.S)
    if not patch:
        problems.append("the finalizer patch string was not found")
    else:
        for path in ("/metadata/uid", "/metadata/labels/team", "/spec/project"):
            if f'"op":"test","path":"{path}"' not in patch.group(1):
                problems.append(f"the finalizer patch no longer tests {path}")
    return problems


# --------------------------------------------------------------------------
# G4: cascade coverage (model of AppProject.IsLiveResourcePermitted, v3.3.8)
# --------------------------------------------------------------------------

def _in_list(group: str, kind: str, entries: list, named: str | None = None) -> bool:
    for e in entries:
        eg, ek = e.get("group", ""), e.get("kind", "")
        if (eg == "*" or eg == group) and (ek == "*" or ek == kind):
            if named is None or not e.get("name") or fnmatch.fnmatchcase(named, e["name"]):
                return True
    return False


def _dest_ok(project: dict, server: str, namespace: str) -> bool:
    for d in (project.get("spec") or {}).get("destinations") or []:
        for key in ("server", "namespace"):
            if str(d.get(key, "")).startswith("!"):
                raise Unreadable("negated destination entries are not modelled")
        if d.get("name"):
            raise Unreadable("destination by name is not modelled; use the server URL form")
        srv, ns = d.get("server", ""), d.get("namespace", "")
        if fnmatch.fnmatchcase(server, srv) and fnmatch.fnmatchcase(namespace, ns):
            return True
    return False


def resource_permitted(project: dict, server: str, res: dict) -> bool:
    spec = project.get("spec") or {}
    group, kind, ns, name = res.get("group", ""), res["kind"], res.get("namespace", ""), res.get("name", "")
    if ns:
        wl = spec.get("namespaceResourceWhitelist")      # None = every kind (Argo semantics)
        bl = spec.get("namespaceResourceBlacklist") or []
        listed = wl is None or (len(wl) != 0 and _in_list(group, kind, wl))
        if not listed or (bl and _in_list(group, kind, bl)):
            return False
        return _dest_ok(project, server, ns)
    wl = spec.get("clusterResourceWhitelist") or []
    bl = spec.get("clusterResourceBlacklist") or []
    return len(wl) != 0 and _in_list(group, kind, wl, name) and not (bl and _in_list(group, kind, bl, name))


def cascade_uncovered(app: dict, project: dict) -> list[dict]:
    """Managed resources of `app` that a cascade delete would leave behind."""
    server = ((app.get("spec") or {}).get("destination") or {}).get("server", "")
    resources = (app.get("status") or {}).get("resources")
    if not isinstance(resources, list):
        raise Unreadable(f"{(app.get('metadata') or {}).get('name')}: no status.resources list")
    return [r for r in resources if not resource_permitted(project, server, r)]


def cli_cascade_coverage(apps_path: str, project_path: str, project_name: str) -> int:
    try:
        apps = json.loads(Path(apps_path).read_text())["items"]
        proj_docs = [d for d in yaml.safe_load_all(Path(project_path).read_text()) if isinstance(d, dict)]
        if "items" in (proj_docs[0] if proj_docs else {}):
            proj_docs = proj_docs[0]["items"]
        projects = [d for d in proj_docs if d.get("kind") == "AppProject"]
        if len(projects) != 1:
            raise Unreadable(f"expected exactly one AppProject in {project_path}, found {len(projects)}")
        selected = [a for a in apps if (a.get("spec") or {}).get("project") == project_name]
        if not selected:
            raise Unreadable(f"no Application in project {project_name}")
        bad = 0
        for app in selected:
            for r in cascade_uncovered(app, projects[0]):
                bad += 1
                print(f"UNCOVERED {app['metadata']['name']}: {r.get('group', '')}/{r['kind']} "
                      f"{r.get('namespace', '')}/{r.get('name', '')}")
        print(f"{len(selected)} Applications checked, {bad} resource(s) a cascade would skip")
        return 1 if bad else 0
    except (OSError, ValueError, KeyError, IndexError, yaml.YAMLError, Unreadable) as exc:
        print(f"UNREADABLE: {exc}", file=sys.stderr)
        return 2


# --------------------------------------------------------------------------
# Repo checks and self-tests
# --------------------------------------------------------------------------

failures: list[str] = []


def check(name: str, cond: bool, detail: str = "") -> None:
    print(f"{'PASS' if cond else 'FAIL'}  {name}")
    if not cond:
        failures.append(f"{name}: {detail}")


def repo_checks(root: Path) -> None:
    appsets = load_appsets(root)
    p = appset_findings(appsets)
    check("G1 every ApplicationSet has its recorded finalizer outcome", not p, "; ".join(p))
    p = name_findings(generated_names(root), handwritten_names(root))
    check("G2 generated Application names are distinct and not hand-written", not p, "; ".join(p))
    p = retire_findings((root / RETIRE).read_text())
    check("G3 retire-service clears finalizers only after the cascade wait, pinned", not p, "; ".join(p))


def mutated_set(base: dict[str, dict], name: str, **policy) -> dict[str, dict]:
    m = copy.deepcopy(base)
    m[name]["spec"].setdefault("syncPolicy", {}).update(policy)
    return m


def selftests(root: Path) -> None:
    base = load_appsets(root)
    # G1 red on the mutations that remove or hide the finalizer
    check("G1 red: preserveResourcesOnDeletion true on apps",
          bool(appset_findings(mutated_set(base, "apps", preserveResourcesOnDeletion=True))))
    check("G1 red: preserveResourcesOnDeletion true on tenants",
          bool(appset_findings(mutated_set(base, "tenants", preserveResourcesOnDeletion=True))))
    m = copy.deepcopy(base)
    m["apps"]["spec"]["template"]["metadata"]["finalizers"] = ["example.invalid/other"]
    check("G1 red: a template finalizer that replaces the resources finalizer", bool(appset_findings(m)))
    m = copy.deepcopy(base)
    m["new-set"] = copy.deepcopy(base["apps"])
    check("G1 red: an ApplicationSet that is not in the table", bool(appset_findings(m)))
    m = copy.deepcopy(base)
    del m["tenants"]
    check("G1 red: a listed ApplicationSet disappears", bool(appset_findings(m)))
    check("G1 red: applicationsSync other than the default",
          bool(appset_findings(mutated_set(base, "apps", applicationsSync="create-only"))))
    check("G1 model: preserve false adds the finalizer, true does not, an own list wins",
          controller_finalizers(False, None) == [RESOURCES_FINALIZER]
          and controller_finalizers(True, None) == []
          and controller_finalizers(False, ["x"]) == ["x"])

    # G2 red on collisions
    gen = generated_names(root)
    check("G2 green: the real tree has no duplicate generated name",
          not name_findings(gen, []), "; ".join(name_findings(gen, [])))
    with tempfile.TemporaryDirectory() as tmp:
        t = Path(tmp)
        for d in ("services/a/b-c", "services/a-b/c", "services/tenant/foo", "tenants/foo"):
            (t / "platform-gitops" / d).mkdir(parents=True)
        g = generated_names(t)
        p = name_findings(g, [])
        check("G2 red: <team>-<service> collides across team boundary (a/b-c vs a-b/c)",
              any("a-b-c" in x for x in p), "; ".join(p))
        check("G2 red: a service named into the tenant-<x> namespace of names (tenant/foo vs tenants/foo)",
              any("tenant-foo" in x for x in p), "; ".join(p))
    check("G2 red: a hand-written Application with a generated name",
          bool(name_findings({"admins-x": ["apps:admins/x"]}, ["admins-x"])))
    check("G2 red: a templated hand-written name matches by pattern",
          bool(name_findings({"otel-eval-foo": ["apps:otel/eval-foo"]}, ["otel-eval-__TPL__"])))
    check("G2 green: an unrelated hand-written name",
          not name_findings({"admins-x": ["apps:admins/x"]}, ["tracing-tempo"]))

    # G3 red on reordering and unpinning
    text = (root / RETIRE).read_text()
    strip = re.search(r"\n[^\n]*PATCH=\$\(printf.*?\n[^\n]*\"\$APP_UID\"[^\n]*\n", text, flags=re.S)
    wait_at = text.find("wait_gone 36")
    check("G3 selftest anchors found", bool(strip) and wait_at > 0)
    if strip and wait_at > 0:
        moved = text.replace(strip.group(0), "\n")
        moved = moved[: moved.find("wait_gone 36")] + strip.group(0) + moved[moved.find("wait_gone 36"):]
        check("G3 red: finalizer patch moved before the wait", bool(retire_findings(moved)))
    check("G3 red: the project test op is dropped from the patch",
          bool(retire_findings(text.replace('{"op":"test","path":"/spec/project",', '{'))))
    check("G3 red: the uid test op is dropped from the patch",
          bool(retire_findings(text.replace('{"op":"test","path":"/metadata/uid",', '{'))))
    check("G3 red: the delete body asks for orphaning",
          bool(retire_findings(text.replace('"preconditions"', '"propagationPolicy":"Orphan","preconditions"'))))
    check("G3 red: the uid precondition is dropped",
          bool(retire_findings(text.replace('"preconditions":{"uid"', '"x":{"uid"'))))
    check("G3 red: a second finalizer patch",
          bool(retire_findings(text + "\nkubectl patch application x --type=merge -p '{\"metadata\":{\"finalizers\":null}}'\n")))
    check("G3 red: the wait is removed", bool(retire_findings(text.replace("wait_gone 36", "true"))))

    # G4 model: green and red
    server = "https://kubernetes.default.svc"
    app = {"metadata": {"name": "t-web"}, "spec": {"destination": {"server": server, "namespace": "t"}},
           "status": {"resources": [
               {"group": "apps", "kind": "Deployment", "namespace": "t", "name": "web"},
               {"group": "", "kind": "Service", "namespace": "t", "name": "web"},
               {"group": "external-secrets.io", "kind": "ExternalSecret", "namespace": "t", "name": "web"}]}}
    proj = {"spec": {"destinations": [{"server": server, "namespace": "t"}],
                     "clusterResourceWhitelist": [],
                     "namespaceResourceWhitelist": [{"group": "", "kind": "*"}, {"group": "apps", "kind": "*"},
                                                    {"group": "external-secrets.io", "kind": "*"}],
                     "namespaceResourceBlacklist": [{"group": "", "kind": "ResourceQuota"}]}}
    check("G4 green: every managed resource is covered", cascade_uncovered(app, proj) == [])

    def uncovered(mut) -> int:
        a, p = copy.deepcopy(app), copy.deepcopy(proj)
        mut(a, p)
        return len(cascade_uncovered(a, p))

    check("G4 red: a blacklisted kind is skipped",
          uncovered(lambda a, p: a["status"]["resources"].append(
              {"group": "", "kind": "ResourceQuota", "namespace": "t", "name": "q"})) == 1)
    check("G4 red: a kind outside the whitelist is skipped",
          uncovered(lambda a, p: p["spec"]["namespaceResourceWhitelist"].pop(1)) == 1)
    check("G4 red: a namespace outside the destinations is skipped",
          uncovered(lambda a, p: p["spec"]["destinations"][0].update(namespace="other")) == 3)
    check("G4 red: a server written in another form is skipped",
          uncovered(lambda a, p: p["spec"]["destinations"][0].update(server="https://other.invalid")) == 3)
    check("G4 red: an empty namespaced whitelist skips everything",
          uncovered(lambda a, p: p["spec"].update(namespaceResourceWhitelist=[])) == 3)
    check("G4 model: an absent whitelist permits every kind (Argo semantics)",
          uncovered(lambda a, p: p["spec"].pop("namespaceResourceWhitelist")) == 0)
    check("G4 red: a cluster-scoped object with an empty cluster whitelist is skipped",
          uncovered(lambda a, p: a["status"]["resources"].append({"group": "", "kind": "Namespace", "name": "t"})) == 1)
    check("G4 green: a cluster-scoped object with a listed kind is covered",
          uncovered(lambda a, p: (a["status"]["resources"].append({"group": "", "kind": "Namespace", "name": "t"}),
                                  p["spec"].update(clusterResourceWhitelist=[{"group": "", "kind": "Namespace"}]))) == 0)
    try:
        cascade_uncovered({"metadata": {"name": "x"}, "spec": {}, "status": {}}, proj)
        check("G4 red: an Application without status.resources is an error, not covered", False)
    except Unreadable:
        check("G4 red: an Application without status.resources is an error, not covered", True)
    with tempfile.TemporaryDirectory() as tmp:
        t = Path(tmp)
        (t / "apps.json").write_text(json.dumps({"items": [dict(app, spec=dict(app["spec"], project="p"))]}))
        (t / "proj.yaml").write_text(yaml.safe_dump(dict(proj, kind="AppProject", metadata={"name": "p"})))
        check("G4 cli: exit 0 when covered", cli_cascade_coverage(str(t / "apps.json"), str(t / "proj.yaml"), "p") == 0)
        bad = copy.deepcopy(proj)
        bad["spec"]["namespaceResourceBlacklist"].append({"group": "apps", "kind": "Deployment"})
        (t / "bad.yaml").write_text(yaml.safe_dump(dict(bad, kind="AppProject", metadata={"name": "p"})))
        check("G4 cli: exit 1 when a cascade would skip a resource",
              cli_cascade_coverage(str(t / "apps.json"), str(t / "bad.yaml"), "p") == 1)
        (t / "broken.json").write_text("{not json")
        check("G4 cli: exit 2 when an input is unreadable",
              cli_cascade_coverage(str(t / "broken.json"), str(t / "proj.yaml"), "p") == 2)
        check("G4 cli: exit 2 when no Application is in the project (not 'all covered')",
              cli_cascade_coverage(str(t / "apps.json"), str(t / "proj.yaml"), "zzz") == 2)


def main(argv: list[str]) -> int:
    if len(argv) >= 2 and argv[1] == "--cascade-coverage":
        if len(argv) != 6 or argv[4] != "--project":
            print(__doc__.split("Run:")[0][-400:], file=sys.stderr)
            return 2
        return cli_cascade_coverage(argv[2], argv[3], argv[5])
    root = ROOT
    if len(argv) == 3 and argv[1] == "--root":
        root = Path(argv[2]).resolve()
    try:
        repo_checks(root)
        selftests(root)
    except Unreadable as exc:
        print(f"UNREADABLE: {exc}", file=sys.stderr)
        return 2
    if failures:
        print(f"\n{len(failures)} failure(s):")
        for f in failures:
            print(f"  - {f}")
        return 1
    print("\nall checks passed")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
